#!/usr/bin/env node
/* ============================================================================
 * tools/sync-netlify-fields.mjs
 * ----------------------------------------------------------------------------
 * Regenerates the hidden Netlify form in index.html from js/schema.js.
 *
 * WHY THIS EXISTS
 * Netlify discovers forms by parsing static HTML at deploy time. The
 * questionnaire is rendered by JavaScript, which Netlify's build parser never
 * sees. Netlify's documented workaround is a hidden static form whose input
 * `name` attributes mirror the JavaScript form. Keeping that mirror in sync by
 * hand is the single most common cause of "my Netlify form lost its fields".
 * This script removes the human from that loop.
 *
 * USAGE
 *   node tools/sync-netlify-fields.mjs          # regenerate
 *   node tools/sync-netlify-fields.mjs --check  # verify only; exit 1 on drift
 * ========================================================================== */

import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, '..');
const INDEX = resolve(ROOT, 'index.html');

const { META, allFields } = await import(new URL('../js/schema.js', import.meta.url).href);

const START = '<!-- NETLIFY-FORM-START -->';
const END = '<!-- NETLIFY-FORM-END -->';

/**
 * Fields that exist for the UI only and are never submitted.
 *
 * Currently empty: `whatsapp_same_as_phone` is submitted, because knowing that
 * the client's WhatsApp is the same as their phone number is genuinely useful
 * when deciding how to make first contact.
 */
const UI_ONLY = new Set();

/** Escape a value for safe inclusion in an HTML attribute or text node. */
function esc(s) {
  return String(s)
    .replace(/&/g, '&amp;')
    .replace(/"/g, '&quot;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;');
}

/** Netlify plumbing that must always be present. */
const PLUMBING = [
  { name: 'bot-field',     kind: 'input', attrs: 'type="text"' },
  { name: 'submission_id', kind: 'input', attrs: 'type="hidden"' },
  { name: 'submitted_at',  kind: 'input', attrs: 'type="hidden"' },
  { name: 'subject',       kind: 'input', attrs: 'type="hidden"' },
];

/** Map a schema field type onto an HTML control for the static mirror. */
function controlFor(field) {
  const { type, options } = field;
  const opts = (options || []).map((o) => `<option value="${esc(o.value)}"></option>`).join('');

  switch (type) {
    case 'textarea': return { tag: 'textarea' };
    case 'sendnothing': return null;
    case 'select':
    case 'radio':
    case 'checkbox':
      // A select registers the field name and keeps the mirror compact.
      return { tag: 'select', multiple: type === 'checkbox', inner: opts };
    case 'toggle':
      return { tag: 'input', attrs: 'type="hidden"' };
    case 'email': return { tag: 'input', attrs: 'type="email"' };
    case 'tel':   return { tag: 'input', attrs: 'type="tel"' };
    case 'url':   return { tag: 'input', attrs: 'type="url"' };
    case 'date':  return { tag: 'input', attrs: 'type="date"' };
    case 'color': return { tag: 'input', attrs: 'type="color"' };
    default:      return { tag: 'input', attrs: 'type="text"' };
  }
}

function buildBlock() {
  const fields = [];
  const seen = new Set();

  for (const f of [...PLUMBING, ...allFields()]) {
    if (seen.has(f.name) || UI_ONLY.has(f.name)) continue;
    seen.add(f.name);
    fields.push(f);
  }

  const lines = [];
  lines.push(START);
  lines.push('  <!--');
  lines.push('    Hidden static mirror of the JavaScript-rendered brief.');
  lines.push('    GENERATED by tools/sync-netlify-fields.mjs — do not edit by hand.');
  lines.push(`    Registered field count: ${fields.length}`);
  lines.push('  -->');
  lines.push(`  <form name="${esc(META.formName)}" method="POST" data-netlify="true"`);
  lines.push('        netlify-honeypot="bot-field" class="netlify-mirror" aria-hidden="true">');
  lines.push(`    <input type="hidden" name="form-name" value="${esc(META.formName)}">`);

  for (const f of fields) {
    const c = f.kind ? { tag: 'input', attrs: f.attrs } : controlFor(f);
    if (!c) continue;

    if (c.tag === 'textarea') {
      lines.push(`    <textarea name="${esc(f.name)}"></textarea>`);
    } else if (c.tag === 'select') {
      lines.push(`    <select name="${esc(f.name)}"${c.multiple ? ' multiple' : ''}>${c.inner || ''}</select>`);
    } else {
      lines.push(`    <input name="${esc(f.name)}" ${c.attrs || 'type="text"'}>`);
    }
  }

  lines.push('  </form>');
  lines.push('  ' + END);
  return lines.join('\n');
}

/* ── Inject ──────────────────────────────────────────────────────────────── */

const html = await readFile(INDEX, 'utf8');
const startIdx = html.indexOf(START);
const endIdx = html.indexOf(END);

if (startIdx === -1 || endIdx === -1 || endIdx < startIdx) {
  console.error(`✖ Could not find the ${START} / ${END} markers in index.html`);
  process.exit(1);
}

const before = html.slice(0, startIdx);
const after = html.slice(endIdx + END.length);
const next = `${before}${buildBlock()}${after}`;

if (process.argv.includes('--check')) {
  if (next !== html) {
    console.error('✖ index.html Netlify form is OUT OF SYNC with js/schema.js');
    console.error('  Fix: node tools/sync-netlify-fields.mjs');
    process.exit(1);
  }
  console.log('✓ Netlify form mirror is in sync with js/schema.js');
  process.exit(0);
}

await writeFile(INDEX, next, 'utf8');
console.log(`✓ Wrote Netlify form mirror to index.html (${next.match(/<input|<textarea|<select/g).length} controls)`);
